import AppKit
import ApplicationServices
import Carbon.HIToolbox
import PointTakenCore

// Pasting a finished annotation into the app the user came from: one step at a time (a picture, then its text),
// each put on the clipboard and ⌘V'd, and the user's clipboard put back afterwards.

/// The clipboard pastes go through: the general one; a scripted test can name a private one.
let capturePasteboard: NSPasteboard = {
    let env = ProcessInfo.processInfo.environment
    if env["POINT_TAKEN_TEST_COMMANDS"] == "1", let name = env["POINT_TAKEN_TEST_PASTEBOARD"], !name.isEmpty {
        return NSPasteboard(name: NSPasteboard.Name(name))
    }
    return .general
}()

/// Whether macOS lets this app press keys in other apps (Accessibility): needed for the automatic paste.
enum PastePermission {
    static var accessibility: Bool { PasteMode.testMode ? false : AXIsProcessTrusted() }
}

/// Test builds never type into another app: a test app launched from a terminal inherits that terminal's
/// Accessibility grant, and ⌘V would land in whatever is in front. Test mode: the test command channel is on, or this
/// isn't the real app's bundle (a bare `swift build` binary). Then no key is ever posted.
enum PasteMode {
    static var testMode: Bool {
        ProcessInfo.processInfo.environment["POINT_TAKEN_TEST_COMMANDS"] == "1" || Bundle.main.bundleIdentifier != PointTaken.bundleID
    }
    /// clipboard managers skip items marked with these (nspasteboard.org)
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// the general clipboard; a test build's own, never the user's
    static let pasteboard: NSPasteboard = {
        guard testMode else { return .general }
        let name = ProcessInfo.processInfo.environment["POINT_TAKEN_TEST_PASTEBOARD"].flatMap { $0.isEmpty ? nil : $0 }
            ?? "pointtaken.test.paste.\(ProcessInfo.processInfo.processIdentifier)"
        return NSPasteboard(name: NSPasteboard.Name(name))
    }()
}

/// The user's clipboard as it was, to put back after the paste.
struct ClipboardSaved {
    let items: [[(NSPasteboard.PasteboardType, Data)]]
    let changeCount: Int

    static func take(_ pb: NSPasteboard = PasteMode.pasteboard) -> ClipboardSaved {
        let items = (pb.pasteboardItems ?? []).map { it in it.types.compactMap { t in it.data(forType: t).map { (t, $0) } } }
        return ClipboardSaved(items: items, changeCount: pb.changeCount)
    }

    func restore(_ pb: NSPasteboard = PasteMode.pasteboard) {
        pb.clearContents()
        let objs: [NSPasteboardItem] = items.compactMap { pairs in
            guard !pairs.isEmpty else { return nil }
            let it = NSPasteboardItem()
            for (t, d) in pairs { it.setData(d, forType: t) }
            return it
        }
        if !objs.isEmpty { pb.writeObjects(objs) }
    }
}

/// Where a sequence's keys go: ⌘V / ⌘↓ posted at the HID level (the frontmost app), or — test builds — to a stand-in.
enum PasteKeys {
    /// eventSourceUserData of every event Point Taken posts here: the smart-paste tap lets them through
    static let marker: Int64 = 0x426C_7572_7453_5021     // "PointTakenSP!"
    static let standInNote = Notification.Name("pointtaken.test.standin")

    enum Key: String {
        case paste, end, right
    }

    static func post(_ k: Key, to pid: pid_t?, pasteboard: NSPasteboard) {
        emit(["event": "paste_key", "key": k.rawValue, "pid": Int(pid ?? 0), "test": PasteMode.testMode])
        if PasteMode.testMode {
            guard let pid else { return }
            DistributedNotificationCenter.default().postNotificationName(
                standInNote, object: nil, userInfo: ["pid": Int(pid), "do": k.rawValue, "pasteboard": pasteboard.name.rawValue],
                deliverImmediately: true)
            return
        }
        let code = CGKeyCode(k == .paste ? kVK_ANSI_V : k == .end ? kVK_DownArrow : kVK_RightArrow)
        let src = CGEventSource(stateID: .hidSystemState)
        for down in [true, false] {
            guard let e = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: down) else { continue }
            e.flags = k == .right ? [] : .maskCommand
            e.setIntegerValueField(.eventSourceUserData, value: marker)
            e.post(tap: .cghidEventTap)
        }
    }
}

/// One step on the clipboard: its types promised, its data given when the app asks — which is how the runner knows
/// the app has read it. Marked transient (clipboard managers skip it).
final class PasteStepProvider: NSObject, NSPasteboardItemDataProvider {
    let step: PasteStep
    var onRead: (() -> Void)?
    init(_ step: PasteStep) { self.step = step }

    var types: [NSPasteboard.PasteboardType] {
        switch step {
        case .image: return [.png, .tiff]
        case .text: return [.string]
        }
    }

    func item() -> NSPasteboardItem {
        let it = NSPasteboardItem()
        it.setDataProvider(self, forTypes: types)
        it.setData(Data(), forType: PasteMode.transient)
        it.setData(Data(), forType: PasteMode.autoGenerated)
        return it
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        var d: Data?
        switch step {
        case .image(let u):
            let png = try? Data(contentsOf: u)
            d = type == .tiff ? png.flatMap { NSBitmapImageRep(data: $0)?.tiffRepresentation(using: .lzw, factor: 0) } : png
        case .text(let s):
            d = Data(s.utf8)
        }
        if let d { item.setData(d, forType: type) }
        emit(["event": "paste_step_read", "type": type.rawValue, "given": d != nil])
        let f = onRead
        onRead = nil
        f?()
    }
}

/// Runs a PasteRun (PointTakenCore) on the clipboard: put, ⌘V, wait for the read, next; then give the clipboard back.
final class PasteRunner {
    static let readTimeout: TimeInterval = 1.5
    /// after the first read: the app may still ask for the step's other type
    static let grace: TimeInterval = 0.15
    static let restoreAfter: TimeInterval = 0.6

    let pb: NSPasteboard
    let pid: pid_t?
    let restore: () -> Void
    var done: ((PasteRun) -> Void)?
    private(set) var model: PasteRun
    private var written = 0
    private var token = 0
    private var provider: PasteStepProvider?
    var stopOnTimeout = false
    var targetStillReady: (() -> Bool)?

    init(steps: [PasteStep], pasteboard: NSPasteboard, pid: pid_t?, restore: @escaping () -> Void) {
        model = PasteRun(steps: steps)
        pb = pasteboard
        self.pid = pid
        self.restore = restore
    }

    /// `prelude`: keys first (a drag's follow-up: ⌘↓ or →, the caret after the picture).
    func start(prelude: [PasteKeys.Key] = []) {
        for k in prelude { PasteKeys.post(k, to: pid, pasteboard: pb) }
        let go = { [self] in perform(model.start()) }
        if prelude.isEmpty { go() } else { DispatchQueue.main.asyncAfter(deadline: .now() + 0.08, execute: go) }
    }

    private func perform(_ actions: [PasteRun.Action]) {
        for a in actions {
            switch a {
            case .put(let step):
                if targetStillReady?() == false {
                    if pb.changeCount == written { restore() }
                    perform(model.handle(.clobbered)); return
                }
                let p = PasteStepProvider(step)
                provider = p
                token += 1
                let t = token
                p.onRead = { [weak self] in
                    DispatchQueue.main.asyncAfter(deadline: .now() + PasteRunner.grace) { self?.event(.read, token: t) }
                }
                pb.clearContents()
                pb.writeObjects([p.item()])
                written = pb.changeCount
                emit(["event": "paste_step", "step": PasteRunner.describe(step)])
            case .paste:
                PasteKeys.post(.paste, to: pid, pasteboard: pb)
                let t = token
                DispatchQueue.main.asyncAfter(deadline: .now() + PasteRunner.readTimeout) { [weak self] in self?.event(.timeout, token: t) }
            case .restore:
                restore()
            }
        }
        if model.state == .restoring {
            token += 1
            let t = token
            DispatchQueue.main.asyncAfter(deadline: .now() + PasteRunner.restoreAfter) { [weak self] in self?.event(.restoreDue, token: t) }
        }
        if model.finished {
            emit(["event": "paste_run", "state": "\(model.state)", "read": model.read, "unconfirmed": model.unconfirmed])
            done?(model)
            done = nil
        }
    }

    private func event(_ e: PasteRun.Event, token t: Int) {
        guard t == token, !model.finished else { return }
        provider?.onRead = nil
        // A timeout in the Board workflow ends the sequence; never blindly continue into a lost field.
        if e == .timeout, stopOnTimeout, pb.changeCount == written {
            restore(); perform(model.handle(.clobbered)); return
        }
        // someone else wrote the clipboard (the user copied): stop, and put nothing back over it
        perform(model.handle(pb.changeCount != written ? .clobbered : e))
    }

    static func describe(_ s: PasteStep) -> String {
        switch s {
        case .image(let u): return "image:" + u.lastPathComponent
        case .text(let t): return "text:\(t.count)"
        }
    }
}
